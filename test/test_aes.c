#include <stdint.h>
#include <stdio.h>
#include <string.h>

#include "aes128.h"

static int failed;

static void check(const char *name, const uint8_t *key, const uint8_t *in, const uint8_t *want)
{
	uint8_t k[16], b[16];
	int i;

	memcpy(k, key, 16);
	memcpy(b, in, 16);
	aes128_encrypt(k, b);
	if (memcmp(b, want, 16) == 0) {
		printf("PASS  %s\n", name);
		return;
	}
	failed = 1;
	printf("FAIL  %s:", name);
	for (i = 0; i < 16; i++)
		printf(" %02x", b[i]);
	printf("\n");
}

int main(void)
{
	/* FIPS-197 appendix C.1 */
	static const uint8_t k1[16] = { 0x00, 0x01, 0x02, 0x03, 0x04, 0x05, 0x06, 0x07,
					0x08, 0x09, 0x0a, 0x0b, 0x0c, 0x0d, 0x0e, 0x0f };
	static const uint8_t p1[16] = { 0x00, 0x11, 0x22, 0x33, 0x44, 0x55, 0x66, 0x77,
					0x88, 0x99, 0xaa, 0xbb, 0xcc, 0xdd, 0xee, 0xff };
	static const uint8_t c1[16] = { 0x69, 0xc4, 0xe0, 0xd8, 0x6a, 0x7b, 0x04, 0x30,
					0xd8, 0xcd, 0xb7, 0x80, 0x70, 0xb4, 0xc5, 0x5a };
	/* IEEE 802.1AE-2006 annex C.1.1: GHASH key H = E_K(0) of the 54-byte packet test */
	static const uint8_t k2[16] = { 0xad, 0x7a, 0x2b, 0xd0, 0x3e, 0xac, 0x83, 0x5a,
					0x6f, 0x62, 0x0f, 0xdc, 0xb5, 0x06, 0xb3, 0x45 };
	static const uint8_t p2[16] = { 0 };
	static const uint8_t c2[16] = { 0x73, 0xa2, 0x3d, 0x80, 0x12, 0x1d, 0xe2, 0xd5,
					0xa8, 0x50, 0x25, 0x3f, 0xcf, 0x43, 0x12, 0x0e };

	check("FIPS-197 C.1 AES-128", k1, p1, c1);
	check("802.1AE C.1.1 hash key", k2, p2, c2);
	return failed;
}
