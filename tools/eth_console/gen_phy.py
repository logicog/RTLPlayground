#!/usr/bin/env python3
"""Extract the RTL8370B PHY patch and long-link tables from a TL-SG108PE V5 flash dump.

    ./gen_phy.py flash_dump.bin > build/phy_patch.h

The tables are Realtek's (SDK PatchChipData and long_link, plus one extra entry
in the TP-Link boot code), so they are read from the user's own flash at build
time instead of being committed.
"""
import sys

PATCH = 0x1432C       # boot code bank 2, 211 {ocp_addr, data} pairs
PATCH_LEN = 211
LONG_LINK = 0x1431C   # 8 per-PHY values for OCP 0xa4b4


def words(b):
    return [int.from_bytes(b[i:i + 2], "big") for i in range(0, len(b), 2)]


d = open(sys.argv[1], "rb").read()
assert len(d) == 0x200000 and d[:2] == b"\x00\x40", "not a TL-SG108PE V5 dump"
patch = words(d[PATCH:PATCH + PATCH_LEN * 4])
long_link = words(d[LONG_LINK:LONG_LINK + 16])
assert patch[:4] == [0xA436, 0x8028, 0xA438, 0x6800] and patch[-2:] == [0xA400, 0x1140], "patch table not found"
assert long_link == [0x0210, 0x03E8, 0x0218, 0x03F0, 0x0220, 0x03F8, 0x0208, 0x03E0], "long_link table not found"

print("/* Generated by gen_phy.py from a flash dump; do not commit. */")
print(f"#define PHY_PATCH_LEN {PATCH_LEN}")
print("static __code const uint16_t phy_patch[PHY_PATCH_LEN][2] = {")
for i in range(0, len(patch), 2):
    print(f"\t{{0x{patch[i]:04x}, 0x{patch[i + 1]:04x}}},")
print("};")
print("static __code const uint16_t long_link[8] = {" + ", ".join(f"0x{v:04x}" for v in long_link) + "};")
